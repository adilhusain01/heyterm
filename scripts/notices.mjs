writeFileSync("THIRD_PARTY_NOTICES.md", `# Third-party notices\n\nHeyTerm ships the packages below, installed with it or compiled into its web page. Each keeps its own licence. Runtime dependencies are installed by npm from their own publishers, not redistributed by HeyTerm; the Claude Agent SDK among them is Anthropic's, under Anthropic's terms. Generated by scripts/notices.mjs.\n\n${lucide}\n\n${sections.join("\n\n")}\n`);
console.log(`Wrote ${sections.length + 1} notices.`);
