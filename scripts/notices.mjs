// Writes THIRD_PARTY_NOTICES.md: the licence of every package HeyTerm ships, either installed with it
// (runtime dependencies) or compiled into its web page, plus the Lucide icons copied into the source.

import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const bundledIntoThePage = ["react", "react-dom", "zustand", "sonner", "@xterm/xterm", "@xterm/addon-fit", "@xterm/addon-webgl", "boring-avatars", "react-markdown", "@fontsource-variable/geist", "@fontsource-variable/geist-mono"];

function tree(args) {
  return JSON.parse(execFileSync("npm", ["ls", "--all", "--json", ...args], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 }));
}

const found = new Map();
function collect(dependencies = {}) {
  for (const [name, info] of Object.entries(dependencies)) {
    if (!info.version || found.has(`${name}@${info.version}`)) continue;
    found.set(`${name}@${info.version}`, name);
    collect(info.dependencies);
  }
}
collect(tree(["--omit=dev"]).dependencies);
collect(tree(bundledIntoThePage).dependencies);

function licenceText(folder) {
  const file = readdirSync(folder).find((entry) => /^(licen[cs]e|copying)(\.|$)/i.test(entry));
  return file ? readFileSync(path.join(folder, file), "utf8").trim() : undefined;
}

const sections = [];
for (const [key, name] of [...found].sort(([left], [right]) => left.localeCompare(right))) {
  const folder = path.join("node_modules", name);
  if (!existsSync(path.join(folder, "package.json"))) continue;
  const manifest = JSON.parse(readFileSync(path.join(folder, "package.json"), "utf8"));
  if (manifest.name === "heyterm") continue;
  const licence = typeof manifest.license === "string" ? manifest.license : (manifest.license?.type ?? "see the package");
  const text = licenceText(folder);
  sections.push(`## ${key}\n\nLicence: ${licence}\n\n${text ? "```\n" + text + "\n```" : ""}`);
}

